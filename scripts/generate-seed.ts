/**
 * Generates supabase/seed.sql from the TypeScript content sources so the
 * database and the code fallbacks never drift.
 *   node scripts/generate-seed.ts
 * The seed contains CONTENT only (markets, sales kit, Sales Center content) —
 * no fake business data. Sales Center rows are version 1 and never overwrite a
 * version published later by staff (on conflict do nothing).
 */
import { writeFileSync } from "node:fs";
import { defaultMarkets } from "../src/content/markets.ts";
import { defaultSalesAssets } from "../src/content/sales-kit.ts";
import { defaultSalesContent } from "../src/content/sales-center/content.ts";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = [
  "-- GENERATED by scripts/generate-seed.ts — do not edit by hand.",
  "-- Content only (markets + sales kit + Sales Center). No fake customers, sales or commissions.",
  "",
];

for (const m of defaultMarkets) {
  lines.push(
    `insert into public.markets (slug, icon, sort, relevance, content) values (${q(m.slug)}, ${q(m.icon)}, ${m.sort}, ${m.relevance ?? 3}, ${q(JSON.stringify(m.content))}::jsonb)` +
      ` on conflict (slug) do update set icon = excluded.icon, sort = excluded.sort, relevance = excluded.relevance, content = excluded.content;`,
  );
}
lines.push("", "delete from public.sales_assets where file_path is null;");
defaultSalesAssets.forEach((a, i) => {
  lines.push(
    `insert into public.sales_assets (product_id, type, locale, title, body, sort) select id, ${q(a.type)}, ${q(a.locale)}, ${q(a.title)}, ${q(a.body ?? "")}, ${i} from public.products where slug = 'studio';`,
  );
});
lines.push("", "-- Sales Center content (V0.3). Active rows are inserted through the publishing guard.",
  "select set_config('studio.publishing', 'on', false);");
const arr = (xs: string[] = []) => `array[${xs.map(q).join(", ")}]::text[]`;
for (const c of defaultSalesContent) {
  lines.push(
    `insert into public.sales_content (kind, key, locale, version, status, product_id, target_key, channel, stage, title, summary, body, tags, sort, published_at)` +
      ` select ${q(c.kind)}, ${q(c.key)}, ${q(c.locale)}, 1, ${q(c.status)}, p.id, ${c.targetKey ? q(c.targetKey) : "null"}, ${c.channel ? q(c.channel) : "null"},` +
      ` ${c.stage ? q(c.stage) : "null"}, ${q(c.title)}, ${c.summary ? q(c.summary) : "null"}, ${q(JSON.stringify(c.body))}::jsonb, ${arr(c.tags)}, ${c.sort ?? 0},` +
      ` ${c.status === "active" ? "now()" : "null"} from public.products p where p.slug = 'studio'` +
      ` on conflict (kind, key, locale, version) do nothing;`,
  );
}
lines.push("select set_config('studio.publishing', 'off', false);");
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), lines.join("\n") + "\n");
console.log(`seed.sql: ${defaultMarkets.length} markets, ${defaultSalesAssets.length} sales assets, ${defaultSalesContent.length} Sales Center items`);
